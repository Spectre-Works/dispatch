"""Frame the DISPATCH Bridge mark for square icon slots."""

from pathlib import Path
from xml.etree import ElementTree as ET

BRAND = Path(__file__).resolve().parents[1] / "assets" / "brand"
ICON = BRAND / "dispatch-icon.svg"
SVG = "http://www.w3.org/2000/svg"


def render_icon():
    ET.register_namespace("", SVG)
    icon = ET.Element(f"{{{SVG}}}svg", {"width": "128", "height": "128", "viewBox": "0 0 128 128"})
    ET.SubElement(icon, f"{{{SVG}}}rect", {"width": "128", "height": "128", "rx": "24", "fill": "#10151c"})
    mark = ET.parse(BRAND / "dispatch-bridge.svg").getroot()
    mark.attrib.update({"x": "16", "y": "16", "width": "96", "height": "96"})
    icon.append(mark)
    ET.indent(icon)
    return (
        b"<!-- SPDX-FileCopyrightText: 2026 SPECTRE WORKS LLC -->\n"
        b"<!-- Generated by tools/generate_dispatch_icon.py -->\n"
        + ET.tostring(icon, encoding="utf-8") + b"\n"
    )


if __name__ == "__main__":
    ICON.write_bytes(render_icon())
