"""Generate firmware data from a zic output directory for an IANA tzdata release."""

import argparse
from datetime import datetime, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

BEGIN = 1735689600  # 2025-01-01 UTC, the earliest controller clock accepts
END = 2556144000  # 2051-01-01 UTC
DAY = 86400


def transitions(file):
    with file.open("rb") as stream:
        zone = ZoneInfo.from_file(stream)

    def offset(epoch):
        seconds = int(datetime.fromtimestamp(epoch, timezone.utc).astimezone(zone)
                      .utcoffset().total_seconds())
        assert seconds % 60 == 0
        return seconds // 60

    previous = offset(BEGIN)
    records = [(BEGIN, previous)]
    # Modern TZDB offset changes are spaced more than a day apart.
    for epoch in range(BEGIN + DAY, END, DAY):
        current = offset(epoch)
        if current != previous:
            low, high = epoch - DAY, epoch
            while high - low > 1:
                middle = (low + high) // 2
                if offset(middle) == previous:
                    low = middle
                else:
                    high = middle
            assert high % 60 == 0  # Tariff intervals split on UTC minute boundaries.
            records.append((high, current))
            previous = current
    assert offset(END - 1) == previous
    return tuple(records)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("zoneinfo", type=Path)
    parser.add_argument("version")
    args = parser.parse_args()
    print("// Generated by tools/generate_controller_timezones.py.")
    print(f"// Public-domain IANA Time Zone Database {args.version}.")
    print("// SPDX-FileCopyrightText: The tz database contributors")
    print("// SPDX-License-Identifier: LicenseRef-IANA-TZDB-Public-Domain")
    print(f"enum {{ TIMEZONE_BEGIN = {BEGIN}u, TIMEZONE_END = {END}u }};")
    groups = {}
    zones = []
    rows = []
    for path in sorted(args.zoneinfo.rglob("*")):
        if not path.is_file():
            continue
        name = path.relative_to(args.zoneinfo).as_posix()
        assert len(name) < 40 and all(ch.isascii() and (ch.isalnum() or ch in "/_+-") for ch in name)
        records = transitions(path)
        if records not in groups:
            groups[records] = len(rows)
            rows.extend(records)
        zones.append((name, groups[records], len(records)))
    assert len(rows) <= 65535
    print("static const timezone_change timezone_changes[] = {")
    for i in range(0, len(rows), 4):
        print("    " + " ".join(f"{{{epoch}u, {minutes}}}," for epoch, minutes in rows[i:i + 4]))
    print("};")
    print("static const dispatch_timezone timezones[] = {")
    for name, first, count in zones:
        print(f'    {{"{name}", {first}, {count}}},')
    print("};")


if __name__ == "__main__":
    main()
